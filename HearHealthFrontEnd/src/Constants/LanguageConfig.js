export const translateGender = (gender, lang = 'VN') => {
  if (!gender) return '';
  const lower = gender.trim().toLowerCase();
  if (lower === 'nam' || lower === 'male') {
    return lang === 'EN' ? 'Male' : 'Nam';
  }
  if (lower === 'nữ' || lower === 'nu' || lower === 'female') {
    return lang === 'EN' ? 'Female' : 'Nữ';
  }
  return gender;
};

export const translateAssessmentTitle = (title, lang = 'VN') => {
  if (!title) return '';
  if (lang !== 'EN') return title;
  const upper = title.toUpperCase();
  if (upper.includes('RẤT CAO')) return 'VERY HIGH RISK';
  if (upper.includes('KHẨN CẤP')) return 'EMERGENCY RISK';
  if (upper.includes('CAO')) return 'HIGH RISK';
  if (upper.includes('TRUNG BÌNH')) return 'MODERATE RISK';
  if (upper.includes('THẤP') || upper.includes('BÌNH THƯỜNG')) return 'LOW RISK';
  return title;
};

